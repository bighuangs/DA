"""语义组合场景下以正确性优先的 SQL 生成路由策略。

确定性编译器仍可用于显式消融和兼容性运行，但能输出完整 AST 不代表已经正确
理解新的自然语言组合。启用模型路由时，生产请求因此按统一策略进入 SQL 模型；
策略本身不依赖评测 case ID 或问题字面量。
"""
from __future__ import annotations

from typing import Any, Mapping

from app.agent_system.agents.nl2sql.semantic_contract import compact_query_contract


MODEL_SQL_POLICY_VERSION = "correctness-first-model-sql-policy-v7"


# Families whose correctness depends on operand direction, nested aggregation,
# partition scope, cohort boundaries, or several coupled output expressions.
# A closed rule-based IR is still retained as validation/context evidence, but
# the final SQL is generated by the model rather than emitted from the template.
