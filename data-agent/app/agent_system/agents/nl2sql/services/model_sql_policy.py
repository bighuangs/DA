def model_sql_blueprint(family: str) -> list[str]:
    """Return bounded relational-grain guidance for an unseen semantic family."""

    return list(MODEL_SQL_BLUEPRINTS.get(str(family or ""), ()))


def _items(value: Any) -> list[Any]:
    return list(value) if isinstance(value, (list, tuple)) else []


def decide_model_sql_policy(
    semantic_ir: Mapping[str, Any] | None,
    query: str = "",
    *,
    query_settings: Any | None = None,
) -> dict[str, Any]:
    """Return a privacy-safe, deterministic SQL-generation decision."""

    ir = dict(semantic_ir or {})
    compiler = dict(ir.get("compiler") or {})
    coverage = dict(ir.get("semantic_coverage") or {})
    family = str(ir.get("semantic_family") or ir.get("intent") or "unknown")
    dimensions = _items(ir.get("dimensions"))
    measures = _items(ir.get("measures"))
    filters = _items(ir.get("filters"))
    detected_slots = [str(item) for item in _items(coverage.get("detected_slots"))]
    unresolved_slots = [str(item) for item in _items(coverage.get("unresolved_slots"))]
    operation_slots = [
        item for item in detected_slots
        if item.startswith("operator:")
    ]
    reason_codes: list[str] = []

    enabled = bool(getattr(query_settings, "complex_sql_llm_enabled", True))
    deterministic_direct_emission_enabled = bool(
        getattr(
            query_settings,
            "deterministic_sql_direct_emission_enabled",
            False,
        )
    )
    deterministic_fallback_allowed = bool(
        getattr(
            query_settings,
            "deterministic_sql_model_fallback_enabled",
            False,
        )
    )
    compiler_supported = bool(compiler.get("supported"))
    compiler_mode = str(compiler.get("mode") or "")
    trusted_simple_compiler = bool(
        compiler_supported
        and not unresolved_slots
        and float(coverage.get("coverage_score") or 0.0) >= 1.0
        and (
            compiler_mode == "deterministic_sqlglot_v2"
        )
    )
    # Correctness-first is the production default.  A compiler-owned IR is
    # still valuable as bounded semantic evidence and for validation, but its
    # self-reported coverage is not sufficient authority to bypass the model.
    # The old fast path is retained behind one explicit ablation/compatibility
    # switch instead of being inferred from benchmark cases or question text.
    if enabled and not deterministic_direct_emission_enabled:
        reason_codes.append("correctness_first_model_generation")
    if not compiler_supported:
        reason_codes.append("deterministic_compiler_unavailable")
    if unresolved_slots:
        reason_codes.append("semantic_coverage_unresolved")
    if not trusted_simple_compiler and family in MODEL_REQUIRED_FAMILIES:
        reason_codes.append(f"high_risk_family:{family}")
    if not trusted_simple_compiler and len(operation_slots) >= 2:
        reason_codes.append("multiple_semantic_operators")
    if not trusted_simple_compiler and family == "aggregate" and len(measures) >= 2:
        reason_codes.append("aggregate_multiple_measures")
    # Two or more grouping dimensions do not by themselves make a plain
    # aggregate semantically risky.  The deterministic compiler already owns
    # this closed shape (dimensions + one measure + bounded joins), and routing
    # it to the model can needlessly consume the request budget after retrieval.
    # Complex multi-dimensional questions are still routed by their operator,
    # multi-measure/filter, family, or total-slot signals below.
    if not trusted_simple_compiler and family == "aggregate" and len(filters) >= 2:
        reason_codes.append("aggregate_multiple_filters")
    if not trusted_simple_compiler and family == "aggregate" and len(detected_slots) >= int(
        getattr(query_settings, "complex_sql_llm_slot_threshold", 6)
    ):
        reason_codes.append("aggregate_slot_budget_exceeded")
    query_text = str(query or "")
    if not trusted_simple_compiler and (
        "累计" in query_text
        and any(marker in query_text for marker in ("达到", "超过", "%", "百分"))
        and any(marker in query_text for marker in ("最少", "至少", "需要", "多少个"))
    ):
        reason_codes.append("lexical_cumulative_threshold")
    if not trusted_simple_compiler and (
        any(marker in query_text for marker in (
            "月均", "周均", "日均", "季均", "年均", "平均",
        ))
        and any(marker in query_text for marker in (
            "高于", "低于", "超过", "少于", "不低于", "不高于",
        ))
        and any(marker in query_text for marker in (
            "数量", "个数", "次数", "月份数", "周数", "天数", "多少", "几个",
        ))
    ):
        reason_codes.append("lexical_partition_average_count")

    use_model = bool(enabled and reason_codes)
    return {
        "schema_version": MODEL_SQL_POLICY_VERSION,
        "enabled": enabled,
        "routing_mode": (
            "correctness_first_model"
            if enabled and not deterministic_direct_emission_enabled
            else (
                "selective_model_compatibility"
                if enabled else "deterministic_only_ablation"
            )
        ),
        "decision": "model_sql" if use_model else "deterministic_sql",
        "use_model": use_model,
        "deterministic_direct_emission_enabled": (
            deterministic_direct_emission_enabled
        ),
        "deterministic_fallback_allowed": deterministic_fallback_allowed,
        "semantic_family": family,
        "compiler_supported": compiler_supported,
        "trusted_simple_compiler": trusted_simple_compiler,
        "slot_count": len(detected_slots),
        "operation_count": len(operation_slots),
        "dimension_count": len(dimensions),
        "measure_count": len(measures),
        "filter_count": len(filters),
        "reason_codes": reason_codes,
        "raw_question_persisted": False,
        "filter_values_persisted": False,
    }


def use_model_sql(
    semantic_ir: Mapping[str, Any] | None,
    *,
    query_settings: Any | None = None,
) -> bool:
    """Read an attached decision or derive the current policy deterministically."""

    ir = dict(semantic_ir or {})
    attached = ir.get("model_sql_policy")
    if isinstance(attached, Mapping):
        return bool(attached.get("use_model"))
    return bool(decide_model_sql_policy(
        ir,
        query_settings=query_settings,
    )["use_model"])


def force_model_sql_policy(
    policy: Mapping[str, Any] | None,
    *,
    reason: str,
) -> dict[str, Any]:
    """Apply an auditable, request-scoped physical-model routing contract.

    This does not alter the production routing policy globally.  It is used by
    trusted internal callers (currently governed model-boundary evaluation)
    when allowing a deterministic compiler short-cut would invalidate the
    measurement itself.
    """

    current = dict(policy or {})
    normalized_reason = str(reason or "runtime_force_model_sql").strip()
    reason_code = f"forced:{normalized_reason}"
    reason_codes = [
        str(value)
        for value in (current.get("reason_codes") or [])
        if str(value).strip()
    ]
    if reason_code not in reason_codes:
        reason_codes.append(reason_code)
    return {
        **current,
        "decision": "model_sql",
        "use_model": True,
        "reason_codes": reason_codes,
        "forced_by_runtime_context": True,
        "force_reason": normalized_reason,
    }


def deterministic_model_fallback_allowed(
    semantic_ir: Mapping[str, Any] | None,
    *,
    runtime_override: bool | None = None,
    query_settings: Any | None = None,
) -> bool:
    """Return whether an explicit experiment may execute a compiler draft.

    Model routing and deterministic fallback are separate decisions.  In the
    production correctness-first mode a budget miss or rejected model
    candidate must surface as a retryable clarification rather than silently
    becoming compiler output.  Ablation/compatibility callers can opt in via
    configuration or an auditable request-scoped runtime override.
    """

    if runtime_override is not None:
        return bool(runtime_override)
    ir = dict(semantic_ir or {})
    policy = ir.get("model_sql_policy")
    if isinstance(policy, Mapping) and "deterministic_fallback_allowed" in policy:
        return bool(policy.get("deterministic_fallback_allowed"))
    return bool(getattr(
        query_settings,
        "deterministic_sql_model_fallback_enabled",
        False,
    ))


def deterministic_draft_is_safe(
    semantic_ir: Mapping[str, Any] | None,
    draft_sql: str | None,
) -> bool:
    """Whether a closed compiler draft may be used when no model can start.

    This is deliberately stricter than merely having SQL text: the compiler
    must declare support and semantic coverage must contain no unresolved
    slots. Unknown or partial compositions therefore still abstain.
    """

    ir = dict(semantic_ir or {})
    compiler = dict(ir.get("compiler") or {})
    coverage = dict(ir.get("semantic_coverage") or {})
    return bool(
        str(draft_sql or "").strip()
        and compiler.get("supported")
        and not _items(coverage.get("unresolved_slots"))
        and float(coverage.get("coverage_score") or 0.0) >= 1.0
    )


def model_semantic_summary(
    semantic_ir: Mapping[str, Any] | None,
    *,
    deterministic_draft_sql: str | None = None,
    query_settings: Any | None = None,
) -> dict[str, Any]:
    """Build bounded semantic evidence for the required SQL-model route.

    A complex IR contains substantially more information than its dimensions
    and measures.  In particular, partition keys, ranking direction, output
    order, filter-only dimensions and zero-denominator policy determine whether
    two syntactically valid queries are semantically equivalent.  Keep those
    fields explicit so the model is revising a closed contract instead of
    reconstructing it from prose alone.
    """

    ir = dict(semantic_ir or {})
    coverage = dict(ir.get("semantic_coverage") or {})

    def compact_rows(name: str, keys: tuple[str, ...]) -> list[dict[str, Any]]:
        rows = _items(ir.get(name))[:12]
        return [
            {key: row.get(key) for key in keys if row.get(key) is not None}
            for row in rows if isinstance(row, Mapping)
        ]

    safe_slot_keys = (
        "registry_rule", "operators", "aggregate_grain", "subquery_grain",
        "calendar_grain", "comparison_mode", "comparison_periods",
        "partition_keys", "order_keys", "rank_type", "rank_direction",
        "rank_windows", "qualified_entity_grains", "top_n", "tie_breaker",
        "window_function", "outer_filter",
        "event_selector", "observation_year", "repeat_threshold",
        "inner_aggregate", "outer_aggregate", "qualifying_aggregate",
        "anti_join_strategy", "boundary_policy", "zero_denominator",
        "empty_result", "output_shape", "result_grain", "output_columns",
        "stable_order_required",
    )
    raw_slots = dict(ir.get("semantic_slots") or {})
    semantic_slots = {
        key: raw_slots[key]
        for key in safe_slot_keys
        if raw_slots.get(key) is not None
    }
    compiler = dict(ir.get("compiler") or {})

    routing = dict(
        ir.get("model_sql_policy")
        or decide_model_sql_policy(ir, query_settings=query_settings)
    )
    model_route = bool(routing.get("use_model"))
    query_contract = compact_query_contract(ir.get("query_contract"))
    guided_model_route = bool(
        model_route and query_contract.get("authority") != "closed"
    )
    return {
        "schema_version": "model-semantic-summary-v4",
        "semantic_family": str(ir.get("semantic_family") or "unknown"),
        "intent": str(ir.get("intent") or "unknown"),
        "required_tables": [
            str(item) for item in _items(ir.get("required_tables"))[:12]
        ] if not guided_model_route else [],
        "dimensions": compact_rows(
            "dimensions", ("logical", "table", "column")
        ) if not guided_model_route else [],
        "measures": compact_rows(
            "measures", ("logical", "function", "table", "column", "alias")
        ) if not guided_model_route else [],
        # Filter values remain in the authorized user question.  Repeating them
        # here is unnecessary; field/operator evidence is enough to prevent a
        # filter-only dimension from leaking into SELECT/GROUP BY.
        "filters": compact_rows(
            "filters", ("logical", "table", "column", "operator", "source")
        ) if not guided_model_route else [],
        "joins": compact_rows(
            "joins",
            (
                "left_table", "left_column", "right_table", "right_column",
                "relationship",
            ),
        ) if not guided_model_route else [],
        "order_by": compact_rows(
            "order_by", ("target", "direction", "nulls")
        ) if not guided_model_route else [],
        "limit": ir.get("limit") if not guided_model_route else None,
        "semantic_slots": semantic_slots if not guided_model_route else {},
        "compiler_contract": {
            "supported": bool(compiler.get("supported")),
            "mode": compiler.get("mode"),
            "template": compiler.get("template"),
        },
        # A model route means the compiler was not trusted as the final
        # semantic authority.  Do not anchor the model on that SQL.  The draft
        # remains process-local for the separately governed budget fallback.
        "deterministic_draft_sql": (
            str(deterministic_draft_sql).strip()[:12000]
            if deterministic_draft_sql and not model_route else None
        ),
        "draft_withheld_from_model": bool(deterministic_draft_sql and model_route),
        "sql_blueprint": (
            model_sql_blueprint(
                str(ir.get("semantic_family") or ir.get("intent") or "unknown")
            )
            if not guided_model_route else {}
        ),
        "detected_slots": [
            str(item)[:120] for item in _items(coverage.get("detected_slots"))[:32]
        ] if not guided_model_route else [],
        "unresolved_slots": [
            str(item)[:120] for item in _items(coverage.get("unresolved_slots"))[:16]
        ] if not guided_model_route else [],
        "routing": routing,
        # One contract is shared by retrieval, planning, generation and
        # validation.  In particular it distinguishes final visible grain from
        # inner aggregation grain and makes denominator scope explicit.
        "query_contract": query_contract,
        "ir_hints_withheld": guided_model_route,
        "ir_hints_withheld_reason": (
            "model_route_parser_not_authoritative"
            if guided_model_route else None
        ),
    }
