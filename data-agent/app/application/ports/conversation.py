"""会话目录、数据上下文、记忆与摘要用例的出站端口。"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Protocol

from app.domain.conversation.errors import ConversationUnavailableError


class ConversationDataContextStore(Protocol):
    async def get(self, chat_id: str) -> object | None: ...

    async def set(
        self,
        chat_id: str,
        *,
        source_mode: str,
        dataset_ids: list[str],
        comparison_intent: str | None,
        mapping_confirmation_id: str | None,
        expected_revision: int | None,
    ) -> object: ...

    async def reset(self, chat_id: str, *, expected_revision: int | None) -> object: ...

    async def snapshot_turn(
        self,
        *,
        chat_id: str,
        turn_id: str,
        revision: int,
        snapshot: dict,
    ) -> None: ...


class ConversationScopeReader(Protocol):
    """判断当前 owner/workspace 是否拥有目标会话。"""

    async def exists(self, chat_id: str) -> bool: ...


class ConversationHistoryStore(Protocol):
    owner_id: str
    workspace_id: str

    async def list_sessions(
        self,
        *,
        status: str,
        limit: int,
        before_at: datetime | None,
        before_id: int | None,
    ) -> Sequence[object]: ...

    async def get_session(self, chat_id: str, **options: object) -> object | None: ...

    async def list_turns(
        self,
        *,
        chat_id: str,
        limit: int,
        before_at: datetime | None,
        before_id: int | None,
    ) -> Sequence[object]: ...

    async def history_by_ids(self, ids: Iterable[int]) -> Mapping[int, object]: ...

    async def turn_snapshots(self, turn_ids: Iterable[str]) -> Mapping[str, dict]: ...

    async def update_session(
        self,
        chat_id: str,
        *,
        title: str | None,
        status: str | None,
    ) -> object | None: ...

    async def soft_delete(self, chat_id: str) -> bool: ...

    async def begin_delete(self, chat_id: str) -> bool: ...

    async def commit(self) -> None: ...

    async def refresh(self, row: object) -> None: ...


class ConversationMemoryRepositoryPort(Protocol):
    async def append_message(self, **values: object) -> object: ...
    async def set_message_status(self, *args: object, **kwargs: object) -> bool: ...
    async def recent_messages(self, chat_id: str, limit: int) -> Sequence[object]: ...
    async def get_checkpoint(self, chat_id: str, **options: object) -> object | None: ...
    async def upsert_checkpoint(self, **values: object) -> object: ...
    async def delete_checkpoint(self, chat_id: str) -> int: ...
    async def reset_working_transcript(self, chat_id: str) -> dict[str, int]: ...
    async def upsert_memory_item(self, values: dict) -> tuple[object, bool]: ...
    async def supersede_active_preferences(self, **values: object) -> list[str]: ...
    async def supersede_active_fact_slot(self, **values: object) -> list[str]: ...
    async def enqueue_projection(self, **values: object) -> None: ...
    async def enqueue_projection_deletes(self, **values: object) -> None: ...
    async def list_active_candidates(self, **options: object) -> Sequence[object]: ...
    async def list_authoritative_by_ids(self, ids: Iterable[str]) -> Sequence[object]: ...
    async def list_chat_memories(self, chat_id: str, *, limit: int) -> Sequence[object]: ...
    async def revoke_chat_memories(self, chat_id: str) -> list[str]: ...
    async def outbox_status(self) -> dict: ...


class ConversationSummaryRepositoryPort(Protocol):
    async def ensure_state(self, chat_id: str, **options: object) -> object: ...
    async def list_uncovered_summary_messages(self, chat_id: str, **options: object) -> Sequence[object]: ...
    async def semantic_facts_for_messages(self, ids: Iterable[int]) -> Sequence[Mapping]: ...
    async def insert_segment_with_signals(self, segment: dict, signals: Sequence[dict]) -> object: ...
    async def advance_state(self, state: object, **values: object) -> None: ...
    async def active_segment_count(self, chat_id: str) -> int: ...
    async def list_active_segments(self, chat_id: str, *, limit: int) -> Sequence[object]: ...
    async def list_authoritative_by_ids(self, chat_id: str, ids: Iterable[str]) -> Sequence[object]: ...
    async def list_signals_for_summaries(self, ids: Iterable[str]) -> Mapping[str, Sequence[object]]: ...
    async def search_signal_ids(self, chat_id: str, signals: Sequence[str], *, limit: int) -> tuple[list[str], dict]: ...
    async def revoke_chat(self, chat_id: str) -> list[str]: ...
    async def status(self, chat_id: str) -> dict: ...


class ConversationLifecycleRepositoryPort(Protocol):
    async def get_session(self, chat_id: str, **options: object) -> object | None: ...
    async def start_turn(self, **values: object) -> object: ...
    async def complete_turn(self, **values: object) -> object: ...
    async def complete_handled_turn(self, **values: object) -> object: ...
    async def fail_turn(self, **values: object) -> object: ...
    async def reset_context(self, chat_id: str) -> bool: ...


class ConversationHistoryWriterPort(Protocol):
    async def save_turn(
        self,
        chat_id: str,
        query: str,
        sql: str,
        result: list,
        **values: object,
    ) -> object: ...


class ConversationMemoryUnitOfWork(Protocol):
    memory: ConversationMemoryRepositoryPort
    summary: ConversationSummaryRepositoryPort
    history: ConversationLifecycleRepositoryPort
    chat_history: ConversationHistoryWriterPort

    async def commit(self) -> None: ...
    async def rollback(self) -> None: ...
    async def summary_projection_backfill_status(self) -> dict[str, int | bool]: ...


class ConversationMemoryPersistence(Protocol):
    def transaction(self) -> AbstractAsyncContextManager[ConversationMemoryUnitOfWork]: ...


class WorkingMemoryCASResult(Protocol):
    updated: bool


class WorkingMemoryPort(Protocol):
    async def get(self, chat_id: str, *, renew_ttl: bool = True) -> dict | None: ...
    async def compare_and_set(self, chat_id: str, **values: object) -> WorkingMemoryCASResult: ...
    async def replace(self, chat_id: str, **values: object) -> None: ...
    async def delete(self, chat_id: str) -> bool: ...
    async def status(self, chat_id: str) -> dict: ...


class ConversationEmbeddingPort(Protocol):
    async def aembed_query(self, text: str) -> object: ...


class ConversationMemorySearchPort(Protocol):
    async def search(self, query: object, **options: object) -> tuple[list[str], dict]: ...
    async def status(self) -> dict: ...


class ConversationMemoryVectorSearchPort(Protocol):
    async def search(self, embedding: object, **options: object) -> tuple[list[str], dict, list[dict]]: ...
    async def status(self) -> dict: ...


class ProjectionNotifier(Protocol):
    def notify(self) -> None: ...
    def status(self) -> dict: ...


class NullProjectionNotifier:
    """未接线 worker 时保持可观测但不产生副作用。"""

    def notify(self) -> None:
        return None

    def status(self) -> dict:
        return {"status": "unavailable", "configured": False}


